def collect():
    net = build_demo()
    ref = net.reference_node()
    state = ref.audit()["state"]
    blocks = [[b.index, len(b.transactions), b.hash, b.nonce, f"{b.mining_ms}", net.nodes[
        next(n for n in net.nodes if net.nodes[n].keys.address == b.miner)].name if b.index else "—"]
              for b in ref.chain]
    campaigns = views.campaigns_view(state)
    big = max(state.donations.values(), key=lambda d: d["amount"])
    trace = views.trace_donation(state, big["id"])
    doc_ok = views.verify_document(ref.chain, state, doc_hash("invoice_drones.txt"))
    doc_bad = views.verify_document(ref.chain, state, doc_hash("invoice_drones_FORGED.txt"))

    attacks = {}
    for remine in (False, True):
        n = build_demo()
        what = n.tamper("lviv", 3, remine=remine)
        audit = n.nodes["lviv"].audit()
        row = next(b for b in audit["blocks"] if b["index"] == 3)
        healed = n.consensus("lviv") and n.nodes["lviv"].audit()["ok"]
        attacks[remine] = {"what": what, "checks": row["checks"], "healed": healed,
                           "next_bad": [b["index"] for b in audit["blocks"] if not b["ok"]]}

    fork = build_demo()
    fork.set_online("cv", False)
    local = fork.mine("cv")
    fork.events.clear()
    olena = next(a for a, x in fork.reference_node().audit()["state"].actors.items() if x["name"] == "Олена Коваль")
    camp = next(iter(fork.reference_node().audit()["state"].campaigns))
    for amount in (1000, 2000):
        fork.submit(olena, "DONATION", {"campaign": camp, "amount": amount})
        fork.mine("kyiv")
    fork.set_online("cv", True)
    fork_events = [e["text"] for e in fork.events if e["kind"] in ("consensus", "net", "block", "sync")]
    same = len({n.tip.hash for n in fork.nodes.values()}) == 1
    return locals()


