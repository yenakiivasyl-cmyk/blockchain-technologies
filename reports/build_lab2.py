"""Звіт до ЛР №2 «Розробка навчальної криптовалюти. Майнінг»."""
from __future__ import annotations

import json

import diagrams
from docgen import Report
from paths import CNU, IMG, OUT, REPORTS, read_src


def cnu(cents):
    return f"{cents / 100:.2f}"


def build() -> str:
    data = json.loads((OUT / "lab2_result.json").read_text(encoding="utf-8"))
    protocol = (OUT / "lab2_protocol.txt").read_text(encoding="utf-8")
    tests = (OUT / "pytest.txt").read_text(encoding="utf-8")
    diagrams.difficulty_chart(data["experiment"])
    diagrams.chain_diagram(data["chain"])
    b1, b2, b3 = data["blocks_mined"]
    tx1 = data["transactions"][0]

    r = Report()
    r.title_page("лабораторної роботи №2", "Розробка навчальної криптовалюти. Майнінг")
    r.toc()

    r.h1("Мета та обладнання")
    r.p("**Мета:** опанувати основні ідеї майнінгу криптовалют — пошук хеш-образу блоку, меншого за "
        "Difficulty Target, перебором «солі» Nonce (Proof-of-Work), підтвердження транзакцій і формування "
        "ланцюжка блоків — на прикладі навчальної криптовалюти CNUCoin.")
    r.p("**Обладнання та ПЗ:** персональний комп'ютер; Python 3.14, `cryptography` 50, SQLite 3.50, Flask 3.1; "
        "виконана ЛР № 1 (база даних CNUCoin з учасниками та першою непідтвердженою транзакцією).")

    r.h1("1. Алгоритм майнінгу")
    r.p("За умовою ЛР Difficulty Target — **хеш-образ блоку має починатися з нуля** (один шістнадцятковий "
        "нуль, тобто перші 4 біти нульові). У реалізації складність є параметром `difficulty` "
        "(кількість провідних нулів), що дає змогу дослідити її вплив (розділ 6).")
    r.image(IMG / "cnu_mining_flow.png", "Блок-схема алгоритму майнінгу CNUCoin", 11)
    r.bullets([
        "Майнер з IsMiner = 1 обирає **першу за датою/часом** непідтверджену транзакцію (TAApproved = 0).",
        "Перевіряє транзакцію: перераховує TAHash з полів і перевіряє ЕЦП відправника.",
        "Конкатенує `TAHash + BlockChainHash попереднього блоку + Nonce`, починаючи з Nonce = 0, "
        "та обчислює SHA-256.",
        "Якщо хеш не починається з нуля — Nonce збільшується на 1, обчислення повторюється.",
        "Знайдений хеш записується в BlockChainHash, Nonce — у BlockChainTable та в транзакцію; "
        "блок підписується ЕЦП майнера (поле BlockAssign).",
        "Транзакція позначається підтвердженою (TAApproved = 1), кошти списуються у відправника і "
        "зараховуються отримувачу; майнер отримує **5 % від суми** як нові монети (запис REWARD від COINBASE).",
        "Отримані кошти стають доступними для витрачання лише після того, як блок увійде до **наступного** "
        "блоку (1 підтвердження), — аналог правила 120 підтверджень у Bitcoin.",
    ], numbered=True)
    r.code(read_src(CNU / "cnucoin" / "mining.py", "def block_payload", "def mine_next"),
           "Лістинг 1 – Proof-of-Work: перебір «солі»")

    r.h1("2. Протокол дій")
    r.p("Дії виконано скриптом `lab2_protocol.py` над копією БД, створеної в ЛР № 1. "
        "Повний протокол роботи програми:")
    r.code(protocol, size=6.8)

    r.h1("3. Результати майнінгу")
    r.p(f"Перша транзакція з ЛР № 1 (TAID 1, Олена → Андрій, {cnu(tx1['TASum'])} CNU) видобута майнером "
        f"«{b1['MinerAlias']}». Як і в прикладі з методичних вказівок («Hello, world!0 … 4250»), "
        "майнер послідовно перебирає значення «солі»:")
    trace = [[n, h, "знайдено" if n == b1["Nonce"] else ""] for n, h in b1["Trace"]]
    if b1["Nonce"] >= len(b1["Trace"]):
        trace += [["…", "…", ""], [b1["Nonce"], b1["BlockChainHash"], "знайдено"]]
    r.table(["Nonce", "SHA-256(TAHash ∥ BlockChainHash ∥ Nonce)", ""], trace,
            "Перебір «солі» під час майнінгу блоку № 1", widths=[1.6, 12.6, 2.8], mono=(1,), size=10)
    r.table(["Блок", "BlockChainHash", "Nonce", "Спроб", "Час, мс", "Майнер", "Винагорода, CNU"],
            [[f"#{b['BlockID']}", b["BlockChainHash"], b["Nonce"], b["Attempts"], f"{b['MiningTimeMs']:.3f}",
              b["MinerAlias"], cnu(b["Reward"])] for b in data["blocks_mined"]],
            "Значення блоків і «солі», час майнінгу", widths=[1.2, 6.0, 1.5, 1.5, 1.6, 2.4, 2.3], mono=(1,), size=9.5)
    r.p(f"Сумарний час майнінгу трьох блоків — "
        f"**{sum(b['MiningTimeMs'] for b in data['blocks_mined']):.3f} мс**. При складності «0» "
        "очікувана кількість спроб — 16 (імовірність того, що випадковий hex-символ дорівнює 0, становить 1/16), "
        "тож блок знаходиться майже миттєво. Блок № 3 випадково має хеш з трьома нулями — це допустимо, "
        "бо умова «починається з 0» виконується.")
    r.image(IMG / "cnu_chain.png", "Сформований ланцюжок блоків: кожен блок містить хеш попереднього", 17)

    r.h1("4. Підтвердження транзакції")
    r.table(["Поле", "До майнінгу (ЛР № 1)", "Після майнінгу"], [
        ["TAApproved", "0", str(tx1["TAApproved"])],
        ["Nonce (TransactionsTable)", "NULL", str(tx1["Nonce"])],
        ["BlockChainHash (блок #1)", "= TAHash (кандидат)", b1["BlockChainHash"]],
        ["PrevHash (блок #1)", "—", b1["PrevHash"]],
        ["MinerID", "—", f"{b1['MinerAlias']} — {b1['MinerID']}"],
        ["BlockAssign (ЕЦП майнера)", "—", b1["BlockAssign"]],
        ["Підтверджень", "—", "2 (блоки #2 і #3)"],
    ], "Транзакція TAID 1, підтверджена в результаті майнінгу", widths=[4.3, 3.6, 9.1], mono=(2,), size=10)
    r.p("Відповідно до п. 5 практичної частини, транзакцію й блок вважаємо остаточно підтвердженими, коли "
        "вони увійшли до наступного блоку. Тому після видобутку блоку № 1 виконано нову транзакцію "
        f"Андрій → Марія (200.00 CNU) і видобуто блок № 2 (майнер «{b2['MinerAlias']}»), а потім транзакцію "
        "Марія → Олена (300.00 CNU) — блок № 3. Протокол фіксує, що одразу після блоку № 1 Андрій **не міг** "
        "витратити отримані 125.50 CNU (вони були заблоковані), а після блоку № 2 ці кошти стали доступними.")
    r.table(["Учасник", "Усього", "Доступно", "Заблоковано"],
            [[a, cnu(b["total"]), cnu(b["spendable"]), cnu(b["locked"])] for a, b in data["balances_after_block1"].items()],
            "Баланси одразу після блоку № 1 (CNU)", widths=[5, 4, 4, 4])
    r.table(["Учасник", "Усього", "Доступно", "Заблоковано"],
            [[a, cnu(b["total"]), cnu(b["spendable"]), cnu(b["locked"])] for a, b in data["final_balances"].items()],
            "Баланси після трьох блоків (CNU)", widths=[5, 4, 4, 4])
    supply = sum(b["total"] for b in data["final_balances"].values())
    r.p(f"Загальна кількість CNU в обігу зросла з 2350.00 до {cnu(supply)} — на суму винагород майнерам "
        f"({cnu(sum(b['Reward'] for b in data['blocks_mined']))} CNU). Так утворюються нові одиниці криптовалюти.")

    r.h1("5. Аудит цілісності та спроба підробки")
    r.p("Модуль `validator.py` незалежно перевіряє кожен блок: хеш транзакції, ЕЦП відправника, зв'язок з "
        "попереднім блоком, Proof-of-Work та ЕЦП майнера. Для чесного ланцюжка всі перевірки успішні. "
        "Потім у копії БД змінено суму транзакції № 1 зі 125.50 на 12 550.00 CNU:")
    r.table(["Блок", "Хеш транзакції", "ЕЦП відправника", "Зв'язок", "PoW", "ЕЦП майнера"],
            [[f"#{b['BlockID']}"] + ["так" if v else "ні (порушено)" for v in b["checks"].values()]
             for b in data["tamper_audit"]["blocks"]],
            "Результат аудиту після підробки суми", widths=[1.5, 3.3, 3.3, 2.6, 2.6, 3.4])
    r.p("Підробку виявлено миттєво: змінені дані не відповідають хеш-образу TAHash, підписаному відправником. "
        "Щоб приховати зміну, зловмиснику довелося б перерахувати TAHash (але тоді не зійдеться ЕЦП, а "
        "приватного ключа Олени в нього немає) і перемайнити всі наступні блоки.")

    r.h1("6. Дослідження впливу складності")
    exp = data["experiment"]
    r.table(["Нулів", "Прогонів", "Очікувано спроб (16^d)", "Середньо спроб", "Середній час, мс", "Макс. час, мс"],
            [[e["difficulty"], e["runs"], f"{e['expected']:,}".replace(",", " "),
              f"{e['avg_attempts']:,.0f}".replace(",", " "), f"{e['avg_ms']:.2f}", f"{e['max_ms']:.2f}"] for e in exp],
            "Залежність часу майнінгу від Difficulty Target", widths=[1.4, 2.3, 3.4, 3, 3.1, 3.3])
    r.image(IMG / "cnu_difficulty.png", "Кількість спроб і час майнінгу залежно від складності (логарифмічна шкала)", 15)
    r.p(f"Кожен додатковий нуль збільшує обсяг роботи приблизно в 16 разів: від ≈ {exp[0]['avg_ms']:.2f} мс "
        f"для одного нуля до ≈ {exp[-1]['avg_ms']:.0f} мс для п'яти. Саме так у Bitcoin регулюють складність, "
        "щоб блок знаходився в середньому за 10 хвилин незалежно від потужності мережі. Розкид часу між "
        "прогонами великий, оскільки майнінг — імовірнісний процес (геометричний розподіл кількості спроб).")

    r.h1("7. Веб-інтерфейс майнінгу")
    r.p("У веб-інтерфейсі майнер обирає себе та складність і натискає «Видобути наступний блок»; "
        "оглядач блоків показує BlockChainHash, PrevHash, Nonce, кількість спроб, час і результат аудиту.")
    r.image(IMG / "cnu_dashboard.png", "Головна сторінка: ланцюжок блоків і форма майнінгу")
    r.image(IMG / "cnu_explorer.png", "Оглядач блоків: BlockChainTable і TransactionsTable з результатами аудиту")

    r.h1("8. Тестування")
    r.code(tests, size=8)

    r.h1("9. Відповіді на контрольні запитання")
    r.qa(1, "Що ми розуміємо під майнінгом криптовалют?", [
        "Майнінг — діяльність із формування нових блоків ланцюжка: майнер збирає непідтверджені транзакції, "
        "перевіряє їх і шукає таке значення Nonce, щоб хеш блоку задовольняв умову складності (Proof-of-Work). "
        "Перший, хто знайшов такий хеш, додає блок до ланцюжка й отримує винагороду новими монетами та "
        "комісіями. У CNUCoin майнінг виконує функція `mine_next()`: вона перебирає Nonce, доки "
        "SHA-256(TAHash ∥ BlockChainHash ∥ Nonce) не почнеться з нуля.",
    ])
    r.qa(2, "Які функції виконує майнінг?", [
        "- **підтвердження транзакцій** — включення їх у блок робить їх частиною незмінної історії;",
        "- **захист від подвійного витрачання** — майнер перевіряє підписи та баланс; конфліктні транзакції не потрапляють у ланцюжок;",
        "- **досягнення консенсусу** — децентралізована мережа погоджується на ланцюжок з найбільшою сумарною роботою;",
        "- **безпека історії** — для зміни блоку треба перевиконати роботу для нього й усіх наступних;",
        "- **емісія** — легальне створення нових одиниць криптовалюти як винагороди;",
        "- **упорядкування в часі** — блоки задають порядок транзакцій без центрального сервера часу.",
    ])
    r.qa(3, "На основі яких криптографічних перетворень працює майнінг?", [
        "Основою є **криптографічна хеш-функція** (SHA-256 у Bitcoin і CNUCoin; у Bitcoin — подвійна SHA-256). "
        "Важливі її властивості: одностороність (неможливо підібрати вхід за виходом інакше як перебором), "
        "лавинний ефект (зміна Nonce на 1 повністю змінює хеш) та рівномірність розподілу виходу. "
        "Також використовуються **дерево Меркла** (корінь хешів транзакцій у заголовку блоку) та **ЕЦП**: "
        "майнер перевіряє підписи відправників, а в CNUCoin ще й підписує видобутий блок (BlockAssign).",
    ])
    r.qa(4, "Чому майнінг криптовалют — важка обчислювальна задача? Для чого це зроблено?", [
        "Знайти хеш із d нулями можна лише перебором: кожна спроба вдала з імовірністю 16^(-d), тож у середньому "
        "потрібно 16^d обчислень (дослід у розділі 6 це підтверджує). Натомість перевірка знайденого блоку — "
        "одне обчислення хешу. Ця асиметрія зроблена навмисно:",
        "- щоб переписати історію, зловмисник має витратити більше обчислювальних ресурсів, ніж уся чесна мережа (захист від атаки 51 %);",
        "- щоб унеможливити спам і атаку Сивіли — право голосу визначається витраченою роботою, а не кількістю вузлів;",
        "- щоб регулювати швидкість емісії й інтервал між блоками (у Bitcoin ≈ 10 хв, складність перераховується кожні 2016 блоків);",
        "- щоб створити економічний стимул: чесний майнінг вигідніший за атаку.",
    ])
    r.qa(5, "Для чого використовують ланцюжок блоків (BlockChain)? Які функції він виконує?", [
        "Блокчейн — це впорядкований список блоків, кожен з яких містить хеш попереднього. Його функції:",
        "- **незмінний журнал** усіх транзакцій: зміна будь-якого блоку змінює його хеш і розриває зв'язок з наступними (продемонстровано в розділі 5);",
        "- **розподілений реєстр**: кожен вузол має повну копію і може самостійно перевірити історію;",
        "- **встановлення порядку** транзакцій і, як наслідок, захист від подвійного витрачання;",
        "- **механізм підтверджень**: що глибше блок у ланцюжку, то дорожче його змінити (кошти в CNUCoin доступні після 1 підтвердження);",
        "- **прозорість і аудит**: будь-хто може перевірити емісію, баланси та всі перекази;",
        "- основа для смарт-контрактів, реєстрів документів та інших застосувань (див. проєкт).",
    ])

    r.h1("Висновки")
    r.p("У лабораторній роботі реалізовано майнінг навчальної криптовалюти CNUCoin за схемою Proof-of-Work. "
        "Майнер з правом IsMiner вибирає першу за часом непідтверджену транзакцію, перевіряє її ЕЦП, перебирає "
        "«сіль» Nonce, доки хеш-образ SHA-256(TAHash ∥ BlockChainHash ∥ Nonce) не почнеться з нуля, підписує блок "
        "і отримує винагороду 5 %. Видобуто три блоки "
        f"(Nonce = {b1['Nonce']}, {b2['Nonce']}, {b3['Nonce']}), транзакцію № 1 підтверджено й остаточно "
        "закріплено наступними блоками; показано блокування отриманих коштів до наступного блоку. "
        "Аудит ланцюжка виявив штучну підробку суми, а експеримент зі складністю підтвердив експоненційне "
        "(×16 на кожен нуль) зростання обчислювальної роботи, що й забезпечує безпеку блокчейну.")

    r.new_page()
    r.h1("Додаток А. Лістинги програмного коду")
    for name in ("mining.py", "validator.py"):
        r.h3(f"cnucoin/{name}")
        r.code(read_src(CNU / "cnucoin" / name), size=7.5)
    return r.save(REPORTS / "ЛР2_CNUCoin_Майнінг.docx")


if __name__ == "__main__":
    print(build())
